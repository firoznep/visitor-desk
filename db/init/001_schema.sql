-- Run once by Postgres on first container start (docker-entrypoint-initdb.d).
-- For an already-running database, apply this with Alembic instead (see backend/migrations).

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE SEQUENCE IF NOT EXISTS badge_seq START 1;

CREATE TABLE departments (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);
CREATE UNIQUE INDEX uq_departments_name_lower ON departments (lower(name));

CREATE TABLE companies (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);
CREATE UNIQUE INDEX uq_companies_name_lower ON companies (lower(name));

CREATE TABLE users (
    id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    username             text UNIQUE NOT NULL,
    full_name            text NOT NULL,
    password_hash        text NOT NULL,
    role                 text NOT NULL CHECK (role IN ('receptionist', 'admin')),
    is_active            boolean NOT NULL DEFAULT true,
    must_change_password boolean NOT NULL DEFAULT false,
    failed_attempts      integer NOT NULL DEFAULT 0,
    locked_until         timestamptz,
    last_login_at        timestamptz,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sessions (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id       uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash    bytea UNIQUE NOT NULL,
    csrf_token    text NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    last_seen_at  timestamptz NOT NULL DEFAULT now(),
    expires_at    timestamptz NOT NULL,
    revoked_at    timestamptz,
    ip            text,
    user_agent    text
);
CREATE INDEX idx_sessions_user ON sessions(user_id);
CREATE INDEX idx_sessions_expiry ON sessions(expires_at) WHERE revoked_at IS NULL;

CREATE TABLE visits (
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    badge_no         text UNIQUE NOT NULL DEFAULT ('V-' || lpad(nextval('badge_seq')::text, 6, '0')),
    visit_date       date NOT NULL,
    full_name        text NOT NULL,
    id_number_enc    text NOT NULL,       -- AES-256-GCM ciphertext, app-layer encrypted. See scripts/decrypt_export.py
    id_number_hash   char(64) NOT NULL,   -- HMAC-SHA256 blind index: equality lookups without decrypting
    id_last4         varchar(4) NOT NULL,
    dob_enc          text NOT NULL,       -- AES-256-GCM ciphertext
    nationality      text NOT NULL,
    gender           text NOT NULL CHECK (gender IN ('Male', 'Female', 'Other')),
    id_expiry        date NOT NULL,
    id_expired       boolean NOT NULL,
    floor            text NOT NULL,
    purpose          text NOT NULL,
    host_name        text,
    department       text,
    phone            text,
    company          text,
    vehicle_plate    text,
    notes            text,
    checked_in_at    timestamptz NOT NULL DEFAULT now(),
    checked_out_at   timestamptz,
    created_by       uuid NOT NULL REFERENCES users(id),
    created_at       timestamptz NOT NULL DEFAULT now(),
    deleted_at       timestamptz,         -- soft delete: hidden from normal views, never removed
    deleted_by       text,
    delete_reason    text
);
CREATE INDEX idx_visits_date ON visits(visit_date);
CREATE INDEX idx_visits_id_hash ON visits(id_number_hash);
CREATE INDEX idx_visits_open ON visits(visit_date) WHERE checked_out_at IS NULL AND deleted_at IS NULL;
CREATE INDEX idx_visits_deleted ON visits(deleted_at) WHERE deleted_at IS NOT NULL;
CREATE INDEX idx_visits_search ON visits USING gin (
    (full_name || ' ' || coalesce(company, '') || ' ' || host_name || ' ' || badge_no) gin_trgm_ops
);

CREATE TABLE audit_logs (
    id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    at        timestamptz NOT NULL DEFAULT now(),
    user_id   uuid,
    username  text,
    action    text NOT NULL,
    target    text,
    detail    text,
    ip        text
);
CREATE INDEX idx_audit_at ON audit_logs(at DESC);

-- Principle of least privilege: the API role can read/write the tables it needs and
-- nothing else (no DDL, no other databases, no superuser). Rotate this password like any
-- other secret; it lives only in the backend's environment, never in the frontend.
DO $$
BEGIN
    EXECUTE format('GRANT CONNECT ON DATABASE %I TO visitor_app', current_database());
END $$;
GRANT USAGE ON SCHEMA public TO visitor_app;
GRANT SELECT, INSERT, UPDATE ON users, sessions, visits TO visitor_app;
GRANT SELECT, INSERT ON departments TO visitor_app;
GRANT SELECT, INSERT ON companies TO visitor_app;
GRANT INSERT, SELECT ON audit_logs TO visitor_app;
GRANT USAGE ON SEQUENCE badge_seq TO visitor_app;
GRANT USAGE, SELECT ON SEQUENCE departments_id_seq TO visitor_app;
GRANT USAGE, SELECT ON SEQUENCE companies_id_seq TO visitor_app;
GRANT USAGE, SELECT ON SEQUENCE audit_logs_id_seq TO visitor_app;
-- No DELETE grant anywhere: even a bug or a compromised API can only soft-delete (UPDATE deleted_at).
